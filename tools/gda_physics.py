"""GDA's physics values (geometry_dash_advance include/physics_defines.h) in our units, for the GDA
physics option (map property Physics = GDA, include/player.h LEVEL_GDA).

GDA keeps speeds in 16.16 fixed point, pixels per frame, the GBA at the Game Boy's ~59.73 Hz; we
keep 8.8: a value / 256. The header is evaluated as written, so nothing is copied by hand.

    python tools/gda_physics.py      prints the values; writes include/gda_physics.h
"""
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = Path.home() / "Downloads" / "geometry_dash_advance-main" / "include" / "physics_defines.h"


def defines():
    env = {"sqrt": math.sqrt, "FLOAT_TO_FIXED": lambda f: f * 65536, "SUBPIXEL_MULTIPLIER": 65536,
           "FIXED_MULTIPLIER": 65536}
    for line in HEADER.read_text().splitlines():
        m = re.match(r"#define (\w+)\s+(.+?)\s*(//.*)?$", line)
        if not m or "(" in m.group(1):
            continue
        try:
            env[m.group(1)] = eval(m.group(2), {"__builtins__": {}}, env)
        except Exception:
            pass
    return env


def v88(x):
    return int(round(x / 256))


# orb / pad kinds as in src/sp_draw.c launch_force: yellow orb, yellow pad, pink orb, pink pad
KINDS = ("YELLOW_ORB", "YELLOW_PAD", "PINK_ORB", "PINK_PAD")
MODES = ("CUBE", "SHIP", "BALL", "UFO")


def main():
    d = defines()
    out = ["/* Generated by tools/gda_physics.py from GDA's include/physics_defines.h - do not edit */",
           "#ifndef GDA_PHYSICS_H", "#define GDA_PHYSICS_H", "", "#include <stdint.h>", "",
           "#ifdef GDA_PHYSICS_TABLES   // (src/sp_draw.c: one copy)",
           "// launches (up = negative), [mini][yellow orb, yellow pad, pink orb, pink pad][cube, ship, ball, ufo]",
           "static const int16_t gda_launch[2][4][4] = {"]
    for mini in (0, 1):
        rows = []
        for k in KINDS:
            vals = []
            for m in MODES:
                name = "%s_%s%s_JUMP_SPEED" % (m, "MINI_" if mini else "", k)
                vals.append(-v88(d[name]))
            rows.append("{ %s }" % ", ".join("%6d" % v for v in vals))
        out.append("    { " + ",\n      ".join(rows) + " },")
    out.append("};")
    blue = []
    for mini in (0, 1):
        f = 0.8 if mini else 1.0
        blue.append("{ %s }" % ", ".join(
            "{ %d, %d }" % (v88(d["%s_BLUE_ORB_INITIAL_SPEED" % m] * f), v88(d["%s_BLUE_PAD_INITIAL_SPEED" % m] * f))
            for m in MODES))
    # per mode values (8.8): name -> GDA expression
    values = [
        ("CUBE_GRAVITY", "CUBE_GRAVITY"), ("CUBE_MAX_FALL", "CUBE_MAX_Y_SPEED"),
        ("CUBE_FIRST_JUMP", "CUBE_FIRST_JUMP_SPEED"), ("CUBE_JUMP", "CUBE_JUMP_SPEED"),
        ("MINI_CUBE_FIRST_JUMP", "CUBE_MINI_FIRST_JUMP_SPEED"), ("MINI_CUBE_JUMP", "CUBE_MINI_JUMP_SPEED"),
        ("SHIP_GRAVITY_HOLD", "SHIP_GRAVITY_BASE"), ("SHIP_GRAVITY_HOLD_FALL", "SHIP_GRAVITY_HOLD_FALL"),
        ("SHIP_GRAVITY_RELEASE_RISE", "SHIP_GRAVITY_AFTER_HOLD"), ("SHIP_GRAVITY_RELEASE_FALL", "SHIP_GRAVITY"),
        ("SHIP_MAX_FALL", "SHIP_MAX_Y_SPEED"), ("SHIP_MAX_RISE", "SHIP_MAX_Y_SPEED_HOLDING"),
        ("MINI_SHIP_GRAVITY_HOLD", "SHIP_MINI_GRAVITY_BASE"), ("MINI_SHIP_GRAVITY_HOLD_FALL", "SHIP_MINI_GRAVITY_HOLD_FALL"),
        ("MINI_SHIP_GRAVITY_RELEASE_RISE", "SHIP_MINI_GRAVITY_AFTER_HOLD"), ("MINI_SHIP_GRAVITY_RELEASE_FALL", "SHIP_MINI_GRAVITY"),
        ("MINI_SHIP_MAX_FALL", "SHIP_MINI_MAX_Y_SPEED"), ("MINI_SHIP_MAX_RISE", "SHIP_MINI_MAX_Y_SPEED_HOLDING"),
        ("BALL_GRAVITY", "BALL_GRAVITY"), ("BALL_MAX", "BALL_MAX_Y_SPEED"), ("BALL_SWITCH", "BALL_SWITCH_SPEED"),
        ("UFO_GRAVITY_RISE", "UFO_GRAVITY_RAISING"), ("UFO_GRAVITY_FALL", "UFO_GRAVITY_FALLING"),
        ("UFO_MAX_FALL", "UFO_MAX_Y_SPEED"), ("UFO_JUMP", "UFO_JUMP_SPEED"),
        ("MINI_UFO_GRAVITY_RISE", "UFO_MINI_GRAVITY_RAISING"), ("MINI_UFO_GRAVITY_FALL", "UFO_MINI_GRAVITY_FALLING"),
        ("MINI_UFO_MAX_FALL", "UFO_MINI_MAX_Y_SPEED"), ("MINI_UFO_JUMP", "UFO_MINI_JUMP_SPEED"),
        ("SCROLL_SPEED_FP", "SPEED_1x"),
    ]
    defs = ["// per frame, 8.8 (GDA value / 256)"] + [
        "#define GDA_%-30s %5d   // %s" % (n, v88(d[e]), e) for n, e in values] + [""]
    at = out.index("#ifdef GDA_PHYSICS_TABLES   // (src/sp_draw.c: one copy)")
    out[at:at] = defs
    out += ["// blue orb / pad: the speed toward the new gravity, [mini][cube, ship, ball, ufo][orb, pad]",
            "static const int16_t gda_blue[2][4][2] = { %s };" % ", ".join(blue), "#endif", "", "#endif", ""]
    path = ROOT / "include" / "gda_physics.h"
    path.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()

"""Builds the sprite tiles of the level complete effect: the expanding discs (translucent in GD:
a dither here) and the twinkling star sparkles.

    python tools/make_end_fx.py

A disc is 31 x 31 px: 4 columns x 2 rows of 8x16 sprites, all drawn from its top left quarter
(2 sprites, 4 tiles) mirrored with the X/Y flip bits (overlapping by a pixel: column / row 15 is
the centre), so all sizes fit in VRAM at once and nothing is uploaded while it plays. Size s uses tiles 4s .. 4s + 3 (column 0: 4s, 4s + 1; column 1:
4s + 2, 4s + 3). The first sizes are solid, then a checkerboard (50%), the last ones sparser (25%):
it fades as it grows. Colour 1 only.
Then the stars, one 8x16 pair each (top tile drawn, bottom blank): END_FX_STAR_BIG, _SMALL.
Output: src/graphics/end_fx_discs.c (bank 12) and include/end_fx_discs.h
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RADII = [3, 5, 7, 9, 11, 13, 15, 16]
SOLID_UNTIL = 2      # sizes 0, 1: solid
SPARSE_FROM = 6      # sizes 6, 7: 25%

# stars: centre at x 3, y 3 (where the death effect's tiny dot is); 2 = the centre colour
STAR_BIG = ["00010000", "00010000", "01121100", "00010000", "00010000"]
STAR_SMALL = ["00000000", "00010000", "00121000", "00010000", "00000000"]


def disc_quarter(r, mode):
    def on(x, y):
        # distance from the disc's centre: pixel 15, shared by both halves (the mirrored sprites
        # overlap by a pixel, so the dither runs on through the middle instead of doubling there)
        if (x - 15) ** 2 + (y - 15) ** 2 > r * r:
            return False
        u, v = 15 - x, 15 - y   # pattern by distance from the centre: the mirrored quarters match
        if mode == "solid":
            return True
        if mode == "sparse":
            return (u & 1) == 1 and (v & 1) == 1
        return ((u + v) & 1) == 1
    data = []
    for col in range(2):
        for y in range(16):
            v = 0
            for x in range(8):
                if on(col * 8 + x, y):
                    v |= 0x80 >> x
            data += [v, 0]
    return data


def star(rows):
    data = []
    for y in range(16):
        row = rows[y - 1] if 1 <= y <= len(rows) else "00000000"
        lo = hi = 0
        for x, c in enumerate(row):
            c = int(c)
            if c & 1:
                lo |= 0x80 >> x
            if c & 2:
                hi |= 0x80 >> x
        data += [lo, hi]
    return data


def main():
    tiles = []
    for i, r in enumerate(RADII):
        mode = "solid" if i < SOLID_UNTIL else ("sparse" if i >= SPARSE_FROM else "checker")
        tiles.append(("disc radius %d (%s)" % (r, mode), disc_quarter(r, mode)))
    tiles.append(("star big", star(STAR_BIG)))
    tiles.append(("star small", star(STAR_SMALL)))
    count = sum(len(d) for _, d in tiles) // 16
    lines = ["/* Generated by tools/make_end_fx.py - do not edit */", "#pragma bank 12", "",
             '#include "end_fx_discs.h"', "",
             "const uint8_t end_fx_tiles[END_FX_TILE_COUNT * 16] = {"]
    for name, d in tiles:
        lines.append("    // " + name)
        for j in range(0, len(d), 16):
            lines.append("    " + ", ".join("0x%02X" % b for b in d[j:j + 16]) + ",")
    lines.append("};")
    (ROOT / "src" / "graphics" / "end_fx_discs.c").write_text("\n".join(lines) + "\n")
    n = len(RADII)
    (ROOT / "include" / "end_fx_discs.h").write_text(
        "/* Generated by tools/make_end_fx.py - do not edit */\n#ifndef END_FX_DISCS_H\n#define END_FX_DISCS_H\n\n"
        "#include <stdint.h>\n\n"
        "#define END_FX_SIZES %d\n"
        "#define END_FX_STAR_BIG %d     // tile offsets from the first tile\n"
        "#define END_FX_STAR_SMALL %d\n"
        "#define END_FX_TILE_COUNT %d\n\n"
        "extern const uint8_t end_fx_tiles[END_FX_TILE_COUNT * 16];\n\n#endif\n"
        % (n, n * 4, n * 4 + 2, count))


main()

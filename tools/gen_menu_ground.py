"""The title menu's ground strip map rows for each of its 64 scroll positions -> src/graphics/menu_ground_map.c

    python tools/gen_menu_ground.py

The ground (state_menu.c draw_ground) is a flat strip with a pillar every 64 px. On DMG its 3 map
rows (32 cells each, written whole in HBlanks) are copied straight from this table instead of
being worked out every frame, which took ~24 scanlines of the DMG menu's frame. The numbers must
match state_menu.c: GROUND_TILE_BASE, GROUND_TILES_PER_ROW, GROUND_ROWS, GROUND_PERIOD.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "graphics" / "menu_ground_map.c"
BANK = 70
TILE_BASE, PER_ROW, ROWS, PERIOD = 1, 16, 3, 64


def rows_at(phase):
    uni = lambda k: TILE_BASE + k * PER_ROW
    rows = [[uni(k)] * 32 for k in range(ROWS)]
    for j in range(3):
        xl = phase + j * PERIOD - 8
        tx, o = xl >> 3, xl & 7
        for k in range(ROWS):
            if 0 <= tx < 20:
                rows[k][tx] = uni(k) + 1 + o
            if o and 0 <= tx + 1 < 20:
                rows[k][tx + 1] = uni(k) + 8 + o
    return sum(rows, [])


def main():
    data = sum((rows_at(p) for p in range(PERIOD)), [])
    lines = ['    ' + ', '.join('%d' % v for v in data[i:i + 32]) + ',' for i in range(0, len(data), 32)]
    OUT.write_text('\n'.join([
        '// Generated by tools/gen_menu_ground.py: do not edit',
        '#pragma bank %d' % BANK, '',
        '#include <gb/gb.h>', '#include <stdint.h>', '',
        'BANKREF(menu_ground_map)',
        '// [scroll position 0..63][row 0..2][map column 0..31]',
        'const uint8_t menu_ground_map[%d] = {' % len(data)] + lines + ['};', '']), newline='\n')
    print('wrote', OUT, len(data), 'bytes')


if __name__ == '__main__':
    main()

"""The mini cube icons of the main menu.

    python tools/make_mini_cube_icons.py

levels/chr_data/game_art/mini_cube_icons.chr (NES CHR, 8x8 icons, blank tiles skipped; colours 1
outline, 2 primary, 3 secondary) -> src/graphics/mini_cube_icons.c: per icon the 3 images the game's
mini cube spins through (0, 22.5 and 45 degrees clockwise), 16 bytes each.
"""
from pathlib import Path

from make_cube_icon_frames import voted

ROOT = Path(__file__).resolve().parent.parent
CHR = ROOT / "levels" / "chr_data" / "game_art" / "mini_cube_icons.chr"
OUT = ROOT / "src" / "graphics" / "mini_cube_icons.c"
ANGLES = [0, 22.5, 45]
COLOURS = {0: 0, 1: 3, 2: 2, 3: 1}   # to the game's: 1 secondary, 2 primary, 3 black (like Famidash's icons)


def decode(tile):
    return [[COLOURS[((tile[y] >> (7 - x)) & 1) | (((tile[y + 8] >> (7 - x)) & 1) << 1)] for x in range(8)]
            for y in range(8)]


def encode(img):
    out = []
    for row in img:
        lo = hi = 0
        for v in row:
            lo = (lo << 1) | (v & 1)
            hi = (hi << 1) | (v >> 1)
        out += [lo, hi]
    return out


def outline(img):
    """Its silhouette's edge redrawn in black: at 8x8 a turned outline breaks up"""
    inside = lambda x, y: 0 <= x < 8 and 0 <= y < 8 and img[y][x] != 0
    return [[3 if v and not all(inside(x + a, y + b) for a, b in ((1, 0), (-1, 0), (0, 1), (0, -1))) else v
             for x, v in enumerate(row)] for y, row in enumerate(img)]


def main():
    d = CHR.read_bytes()
    tiles = [d[i:i + 16] for i in range(0, len(d), 16) if any(d[i:i + 16])]
    data = []
    for t in tiles:
        for angle, img in zip(ANGLES, voted(decode(t), ANGLES, black=1.0)):
            data += encode(img if angle == 0 else outline(img))
    text = ['#pragma bank 29', '// Generated by tools/make_mini_cube_icons.py. Do not edit.', '',
            '#include <gb/gb.h>', '#include <stdint.h>', '', 'BANKREF(mini_cube_icons)',
            f'const uint8_t mini_cube_icons[{len(data)}] = {{']
    for i in range(0, len(data), 16):
        text.append('    ' + ', '.join(f'0x{v:02X}' for v in data[i:i + 16]) + ',')
    text += ['};', '']
    OUT.write_text('\n'.join(text))
    print(f'{len(tiles)} icons, {len(data)} bytes -> {OUT.name}')


if __name__ == '__main__':
    main()
